export const formatById = (id: string) => FORMATS.find(f => f.id === id)
// the API names a tournament's format 'WSDC' | 'APF' | 'POPPER' | 'BP' | 'LD' | 'PF' | 'ASIAN' | 'AUSTRALS'; the description here has the same id in lower case
export const formatOfTournament = (code?: string) => formatById((code ?? 'WSDC').toLowerCase()) ?? FORMATS[0]
// formats a tournament can be created with
export const TOURNAMENT_FORMATS = ['WSDC', 'APF', 'POPPER', 'BP', 'LD', 'PF', 'ASIAN', 'AUSTRALS'] as const

// the window when points of information are allowed, in seconds from the start of the speech (null = no POIs)
export function poiWindow(f: Format, s: Speech): [number, number] | null {
  const len = s.minutes * 60
  // formats without points of information: cross-examinations instead (Popper, LD, PF), or none at all (Australs)
  if (['popper', 'ld', 'pf', 'australs'].includes(f.id) || s.side === 'q') return null
  if (f.id === 'asian' && s.minutes < 7) return null // reply speeches
  if (f.id === 'wsdc' && s.minutes < 8) return null // reply speeches
  if (f.id === 'apf' && s.minutes < 7) return null // rebuttals
  return [60, len - 60]
}
