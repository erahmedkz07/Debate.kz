export const regionByCode = (code?: string | null) => REGIONS.find(r => r.code === code)
// the region of a city typed or chosen earlier (cities are stored by their Russian name)
export const regionOfCity = (city: string) => REGIONS.find(r => r.cities.some(c => c.ru === city))
// a city's name in the reader's language (a typed-in village stays as it was typed)
export const cityName = (city: string, lang: 'ru' | 'kz') => {
  for (const r of REGIONS) {
    const c = r.cities.find(x => x.ru === city)
    if (c) return c[lang]
  }
  return city
}
